import { describe, it, expect } from "vitest";
import { detectSacred } from "../lib/sacred";

describe("detectSacred", () => {
  it("ловит басмалу", () => {
    expect(detectSacred("Бисмилляхи-р-рахмани-р-рахим")).not.toBeNull();
  });

  it("ловит арабское письмо", () => {
    expect(detectSacred("Он сказал بِسْمِ اللَّهِ")).not.toBeNull();
  });

  it("ловит ссылку на аят", () => {
    expect(detectSacred("В суре Аль-Бакара аят 255 сказано")).not.toBeNull();
  });

  it("обычную фразу со словом Аллах не трогает", () => {
    expect(detectSacred("Аллах любит терпеливых")).toBeNull();
  });

  it("обычную фразу про молитву не трогает", () => {
    expect(detectSacred("Читай эту дуа после молитвы")).toBeNull();
  });
});

// Границы решены сознательно в пользу того, чтобы НЕ утопить весь ролик
// в ручном вводе: ловим только то, в чём достаточно уверены, что это
// прямая передача сакрального текста, а не разговор о религии вообще.
describe("detectSacred — спорные случаи на границе", () => {
  it("такбир вне списка зачинов не ловит — это ходовое восклицание, а не рецитация", () => {
    // «Аллаху Акбар» — литургическая формула, но настолько частая в
    // обычной речи (эмоциональное восклицание), что попадание в OPENERS
    // увело бы в ручной ввод слишком много обычных реплик.
    expect(detectSacred("Аллаху Акбар, сказал он с радостью")).toBeNull();
  });

  it("хадис, приписанный сподвижнику (не составителю свода), не ловится — известный пробел", () => {
    // HADITH распознаёт передачу только по именам составителей сводов
    // (Бухари, Муслим, Тирмизи, Абу Дауд). Имя сподвижника-передатчика
    // (Абу Хурайра и т.п.) в списке не учтено — такая цитата хадиса
    // проскочит мимо детектора. Задокументировано как известный риск,
    // а не тихий баг.
    expect(detectSacred("Как рассказывал Абу Хурайра, Пророк сказал так")).toBeNull();
  });

  it("хадис с именем составителя свода ловится", () => {
    expect(detectSacred("Передал Бухари от Абу Хурайры")).not.toBeNull();
  });

  it("упоминание суры с числом ловится даже без прямой цитаты — это осознанная сверхчувствительность", () => {
    // «Сура X состоит из N аятов» — не цитата, а справочный факт о Коране,
    // но CITATION реагирует на пару «сура/аят» + число рядом. Решение —
    // ложные срабатывания здесь дешевле: лучше лишний раз попросить
    // человека напечатать обычное предложение руками, чем один раз
    // пропустить настоящую цитату аята мимо тасхиха.
    expect(detectSacred("Сура Аль-Фатиха состоит из 7 аятов")).not.toBeNull();
  });

  it("число без слов сура/аят рядом не ловится", () => {
    expect(detectSacred("У него было 7 детей и большая семья")).toBeNull();
  });
});
