// Аяты, дуа и хадисы машине не отдаются: перевод священного текста — это
// вопрос тасхиха, а не качества модели. Распознали — просим текст руками.
const ARABIC = /[؀-ۿݐ-ݿﭐ-﷿ﹰ-﻿]/;

const OPENERS = [
  "бисмилля", "бисмиллях", "а'узу", "аузубилля", "субханака",
  "аллахумма", "ля иляха илля",
];

// Обычный \b в JS размечает границы только по ASCII \w ([A-Za-z0-9_]) —
// кириллица в него не входит, поэтому \bсура\b никогда не совпадёт со
// словом «сура» ни в каком контексте (переход "пробел → кириллица" для
// движка не граница, обе стороны для него "не-word"). Граница задаётся
// вручную через отрицательный lookaround по \p{L}\p{N} с флагом u.
const NB = "\\p{L}\\p{N}"; // не-буква/не-цифра — ручная замена \b для юникода
const CITATION = new RegExp(
  `(?<![${NB}])(сур[аеы]|аят[аеу]?)(?![${NB}])[^.]{0,40}(?<![${NB}])\\d{1,3}(?![${NB}])`,
  "iu"
);
const HADITH = new RegExp(
  `(?<![${NB}])(передал|сообщил)(?![${NB}]).{0,30}(?<![${NB}])(бухари|муслим|тирмизи|абу дауд)(?![${NB}])`,
  "iu"
);

export function detectSacred(ru: string): string | null {
  if (ARABIC.test(ru)) return "арабский текст — впиши перевод руками";
  const low = ru.toLowerCase();
  if (OPENERS.some((o) => low.includes(o))) {
    return "богослужебная формула — впиши текст руками";
  }
  if (CITATION.test(ru)) return "ссылка на аят — впиши текст руками";
  if (HADITH.test(ru)) return "хадис — впиши текст руками";
  return null;
}
